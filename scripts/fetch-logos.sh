#!/bin/bash
# Downloads Google product logos into logos/ and writes logos/manifest.js.
# Personal use only — logos are gitignored and never published.
set -u
cd "$(dirname "$0")/.."
mkdir -p logos
TMP=$(mktemp -d)
MIN=64
ok=(); missing=()
while read -r id urls; do
  [[ -z "$id" || "$id" == \#* ]] && continue
  got=""
  for u in $urls; do
    curl -sfL --max-time 10 -o "$TMP/$id" "$u" || continue
    sips -s format png "$TMP/$id" --out "$TMP/$id.png" >/dev/null 2>&1 || continue
    w=$(sips -g pixelWidth "$TMP/$id.png" 2>/dev/null | awk '/pixelWidth/{print $2}')
    if [[ -n "$w" && "$w" -ge $MIN ]]; then mv "$TMP/$id.png" "logos/$id.png"; got=1; break; fi
  done
  if [[ -n "$got" ]]; then ok+=("$id"); else missing+=("$id"); rm -f "logos/$id.png"; fi
done < scripts/logo-sources.txt
{
  echo "/* Generated by scripts/fetch-logos.sh — do not edit */"
  echo "(function (root) { root.GH = root.GH || {}; root.GH.logos = {"
  for id in "${ok[@]}"; do echo "  \"$id\": \"logos/$id.png\","; done
  echo "}; })(typeof window !== 'undefined' ? window : globalThis);"
} > logos/manifest.js
rm -rf "$TMP"
echo "logos: ${#ok[@]} ok"
echo "missing: ${missing[*]:-none}"
